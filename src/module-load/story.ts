export interface ModuleStoryState {
  beatId: (typeof timeline.beats)[number]['id']
  context: 'login01' | 'gpu01'
  loadedModule: 'cuda/12.8' | null
  commandNotFound: boolean
  resolvedExecutable: boolean
  batchStatus: 'idle' | 'starting' | 'loaded' | 'running'
  activeWires: readonly ModuleWire[]
  note: {
    anchor: ModulePart
    title: string
    text: string
    command?: string
  }
}

export function frameAt(elapsedMs: number): ModuleStoryState {
  const { beat, withinBeat: t } = timeline.beatAt(elapsedMs)

  switch (beat.id) {
    case 'missing': {
      const missed = t >= 2400
      return {
        beatId: 'missing',
        context: 'login01',
        loadedModule: null,
        commandNotFound: missed,
        resolvedExecutable: false,
        batchStatus: 'idle',
        activeWires: t < 400 ? [] : t < 1350 ? ['login-env'] : ['login-env', 'env-os'],
        note: !missed
          ? {
            anchor: 'login',
            title: 'Fresh shell searches default PATH',
            text: 'Running nvcc checks the directories listed in PATH—initially only base OS paths like /usr/bin.',
            command: 'nvcc --version',
          }
          : {
            anchor: 'spack',
            title: 'Installed on HPC, not in /usr/bin',
            text: 'CUDA 11.8 and 12.8 already sit in Spack prefixes side by side so projects never conflict.',
            command: 'module avail cuda',
          },
      }
    }

    case 'load': {
      const mutated = t >= 2600
      return {
        beatId: 'load',
        context: 'login01',
        loadedModule: mutated ? 'cuda/12.8' : null,
        commandNotFound: false,
        resolvedExecutable: false,
        batchStatus: 'idle',
        activeWires: mutated ? ['login-lmod', 'lmod-env'] : ['login-lmod'],
        note: !mutated
          ? {
            anchor: 'lmod',
            title: 'module load reads a Lua recipe',
            text: 'Lmod looks up the cuda/12.8 modulefile instead of installing or copying any package.',
            command: 'module load cuda/12.8',
          }
          : {
            anchor: 'env',
            title: 'Pointers change, binaries stay put',
            text: 'Lmod prepends cuda-12.8/bin to PATH and sets CUDA_HOME and build paths inside this shell.',
            command: 'module list',
          },
      }
    }

    case 'resolve': {
      const resolved = t >= 2200
      const compare = t >= 4100
      return {
        beatId: 'resolve',
        context: 'login01',
        loadedModule: 'cuda/12.8',
        commandNotFound: false,
        resolvedExecutable: resolved,
        batchStatus: 'idle',
        activeWires: t < 1100 ? ['login-env'] : ['login-env', 'env-spack'],
        note: !compare
          ? {
            anchor: 'spack',
            title: 'Prepended PATH resolves 12.8 first',
            text: 'The shell checks cuda-12.8/bin ahead of /usr/bin and runs the exact CUDA toolkit you chose.',
            command: 'which nvcc && nvcc --version',
          }
          : {
            anchor: 'lmod',
            title: 'Switch versions without root',
            text: 'Need 11.8 for older code? Switching modules rewires shell variables while both builds coexist.',
            command: 'module switch cuda/12.8 cuda/11.8',
          },
      }
    }

    case 'batch': {
      const batchLoaded = t >= 3000
      const batchRunning = t >= 4300
      return {
        beatId: 'batch',
        context: 'gpu01',
        loadedModule: batchLoaded ? 'cuda/12.8' : null,
        commandNotFound: false,
        resolvedExecutable: batchRunning,
        batchStatus: batchRunning ? 'running' : batchLoaded ? 'loaded' : 'starting',
        activeWires: !batchLoaded
          ? (t >= 2300 ? ['batch-lmod'] : [])
          : batchRunning
            ? ['batch-env', 'env-spack']
            : ['batch-lmod', 'lmod-env'],
        note: t < 2700
          ? {
            anchor: 'batch',
            title: 'Batch jobs start a distinct shell',
            text: 'sbatch runs job.sh in its own shell on a compute node, separate from your login01 terminal.',
            command: 'sbatch job.sh',
          }
          : {
            anchor: 'env',
            title: 'Establish modules inside job.sh',
            text: 'Loading modules in job.sh ensures the compute shell wires the right PATH and CUDA_HOME every run.',
            command: 'module purge && module load cuda/12.8',
          },
      }
    }
  }
}
